import { UNVERIFIED_GAP, WEIGHTS_CHECKS } from '../../src/planner/weights-verification';
import { noticeText } from './notice-lib';

const root = path.resolve(import.meta.dirname, '..', '..');
const read = (p: string) => JSON.parse(readFileSync(path.join(root, p), 'utf8')) as unknown;
const docs = path.join(root, 'docs');
const GENERATED = '<!-- Generated by `npm run dev:docs` from the repository data. Do not edit by hand. -->';

const hw = hardwareFileSchema.parse(read('data/hardware.json'));
const refs = referencesFileSchema.parse(read('data/references.json'));
const gpus = new Map(hw.gpus.map((g) => [g.id, gpuFromSpec(g)]));
const gpuName = (id: string) => gpus.get(id)?.name ?? id;

type Point = {
  id: string;
  engine: 'vllm' | 'sglang';
  repo: string;
  gpu: string;
  tp: number;
  pp: number;
  concurrency: number;
  inputLen: number;
  outputLen: number;
  kv: 'fp8' | 'auto';
  decodeTokSPerUser?: number;
  ttftMs?: number;
  basis: 'decode' | 'tpot' | 'throughput';
};
const points = read('test/fixtures/calibration-points.json') as {
  profiles: Record<string, { profile: ModelProfile; layout: KvLayout; weights: ParallelShape['weights']; family: string; sparseTopk?: number }>;
  points: Point[];
};

const md = (s: unknown) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const num = (n: number | null | undefined, digits = 1) => (n === null || n === undefined ? '—' : n.toLocaleString('en-US', { maximumFractionDigits: digits }));
const pct = (x: number) => `${x >= 0 ? '+' : ''}${(x * 100).toFixed(1)} %`;
const tok = (n: number) => (n >= 1024 * 1024 ? `${num(n / 1048576)}M` : n >= 1024 ? `${num(n / 1024)}K` : String(n));
const table = (head: string[], rows: unknown[][]) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(md).join(' | ')} |`)].join('\n');
const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? (s[m] as number) : ((s[m - 1] as number) + (s[m] as number)) / 2;
};

/** The same prediction as test/planner/calibration-points.test.ts. */
function predict(p: Point) {
  const m = points.profiles[p.repo];
  const gpu = gpus.get(p.gpu);
  if (!m || !gpu) throw new Error(`missing ${p.repo} / ${p.gpu}`);
  const layout = { gpu, count: p.tp * p.pp, tp: p.tp, pp: p.pp };
  const cal = calibrationFor(p.engine, gpu, m.weights, m.family);
  const elem = kvElementBytes(p.engine, p.kv);
  const kvRead = kvReadBytes(m.layout, elem, p.tp, p.inputLen + p.outputLen / 2, m.sparseTopk);
  const batched = schedulerDefaults(p.engine, gpu.cudaMiB.max, p.tp).batchedTokens;
  const speed = {
    stepMs: (b: number) => decodeStepMs({ profile: m.profile, layout, batch: b, kvBytesPerSeq: kvRead, weights: m.weights, cal }),
    prefillMs: (t: number) => prefillMs({ profile: m.profile, layout, tokens: t, batchedTokens: batched, weights: m.weights, cal }),
    batchedTokens: batched,
    requestOverheadMs: cal.requestOverheadMs,
  };
  const step = speed.stepMs(p.concurrency);
  const single = speed.prefillMs(p.inputLen);
  const lp = loadPoint(speed, { maxContext: p.inputLen + p.outputLen, typicalContext: p.inputLen, outputTokens: p.outputLen, minTokS: 0, maxTtftMs: 0, activeShare: 1, safety: 1, cachedShare: 0 }, p.concurrency);
  return {
    decode: p.basis === 'decode' ? { min: 1000 / step.max, max: 1000 / step.min } : p.basis === 'tpot' ? { min: lp.tokS.min, max: 1000 / step.min } : lp.tokS,
    ttft: p.concurrency > 1 ? lp.ttftMs : { min: single.min + cal.requestOverheadMs.min + step.min, max: single.max + cal.requestOverheadMs.max + step.max },
    speedKnown: gpu.tflops.bf16 !== null && gpu.bandwidthGBs > 0,
    weights: m.weights,
    family: ({ dense: 'dense', moe: 'MoE', hybrid: 'hybrid', mla: 'MLA' } as Record<string, string>)[speedFamily(m.family)] as string,
    spread: cal.spread ?? { decode: 0, prefill: 0 },
  };
}

// A. Calibration runs on the RTX 5090.
function appendixA(): string {
  type Run = { name: string; repo: string; layers: number | null; date: string; maxModelLen: number; maxNumSeqs: number; kvTokens?: number; startupS?: number; seconds: number; disturbed?: string; note?: string; ttft?: { promptTokens: number; medianMs: number }[]; decode?: { inputLen: number; batch: number; tokSPerUser: number }[]; long?: { promptTokens: number; ttftMs: number; decode: { batch: number; tokSPerUser: number; serverItlMs?: number }[] }[] };
  const speed = read('test/fixtures/rtx5090/speed.json') as { engineVersion: string; runs: Run[] };
  const long = read('test/fixtures/rtx5090/speed-long.json') as { engineVersion: string; runs: Run[] };
  const mem = read('test/fixtures/rtx5090/measurements.json') as { runs: { name: string; repo: string; layers: number | null; date: string; maxModelLen: number; seconds: number; ok: boolean; format: string; family: string; calculatedGiB: number; lines: string[] }[] };
  const runRow = (r: Run) => [r.date, r.repo, r.layers ?? 'all', tok(r.maxModelLen), r.maxNumSeqs, num(r.kvTokens, 0), r.startupS ?? '—', r.seconds, r.disturbed ? `excluded: ${r.disturbed}` : 'used'];
  const head = ['Date', 'Model', 'Layers', 'max-model-len', 'max-num-seqs', 'KV tokens', 'Start-up (s)', 'Run (s)', 'Status'];
  const ttft = speed.runs.flatMap((r) => (r.ttft ?? []).map((t) => [r.name, r.repo, tok(t.promptTokens), num(t.medianMs, 0)]));
  const dec = speed.runs.flatMap((r) => (r.decode ?? []).map((d) => [r.name, r.repo, tok(d.inputLen), d.batch, num(d.tokSPerUser)]));
  const lng = long.runs.flatMap((r) => (r.long ?? []).flatMap((l) => l.decode.map((d) => [r.name, r.repo, tok(l.promptTokens), num(l.ttftMs, 0), d.batch, num(d.tokSPerUser), num(d.serverItlMs, 2)])));
  const loading = (lines: string[]) => /Model loading took ([\d.]+) GiB/.exec(lines.join('\n'))?.[1];
  return [
    '# Appendix A. Calibration runs on the RTX 5090',
    '',
    GENERATED,
    '',
    `Calibration runs on one RTX 5090 (32 GB; Windows 11 + WSL2, vLLM ${speed.engineVersion} in Docker), dummy weights, fp8 KV cache. Runs disturbed by other programs using the CPU are kept with the reason and excluded from the fit. Reproduce with \`npm run dev:speed\` and \`npm run dev:measure\` (scripts/dev/README.md).`,
    '',
    `GPU time of this calibration: ${num((speed.runs.concat(long.runs).reduce((a, r) => a + r.seconds, 0) + mem.runs.reduce((a, r) => a + r.seconds, 0)) / 3600, 1)} h over ${speed.runs.length + long.runs.length + mem.runs.length} runs (${speed.runs.filter((r) => r.disturbed).length + long.runs.filter((r) => r.disturbed).length} speed runs excluded), plus engine start-up.`,
    '',
    '## A.1 Speed runs (4K–32K prompts, 1–32 concurrent requests)',
    '',
    table(head, speed.runs.map(runRow)),
    '',
    '### Time to first token (median of 3)',
    '',
    table(['Run', 'Model', 'Prompt', 'TTFT (ms)'], ttft),
    '',
    '### Generation speed per user',
    '',
    table(['Run', 'Model', 'Context', 'Concurrent requests', 'tok/s per user'], dec),
    '',
    '## A.2 Long-context runs',
    '',
    table(head, long.runs.map(runRow)),
    '',
    table(['Run', 'Model', 'Prompt', 'TTFT (ms)', 'Concurrent requests', 'tok/s per user', 'Server ITL (ms)'], lng),
    '',
    '## A.3 Memory runs (weights loaded by vLLM against the computed weights)',
    '',
    table(
      ['Date', 'Model', 'Layers', 'Format', 'Family', 'max-model-len', 'Run (s)', 'vLLM "Model loading took" (GiB)', 'Computed (GiB)'],
      mem.runs.map((r) => [r.date, r.repo, r.layers ?? 'all', r.format, r.family, tok(r.maxModelLen), r.seconds, loading(r.lines) ?? (r.ok ? '—' : 'failed'), num(r.calculatedGiB, 3)]),
    ),
    '',
  ].join('\n');
}

// B. Public benchmarks.
function appendixB(): string {
  const used = new Set(points.points.map((p) => p.id.replace(/-(dec|ttft|tpot).*$/, '')));
  const pointIds = points.points.map((p) => p.id);
  const role = (id: string) => {
    const outlier = CALIBRATION_CHECK.outliers[id] ?? CALIBRATION_CHECK.weightOutliers[id];
    if (outlier) return `excluded: ${outlier}`;
    if (pointIds.some((p) => p === id || p.startsWith(`${id}-`)) || used.has(id)) return 'speed: fit and validation';
    return 'memory lines only';
  };
  const rows = refs.entries.map((e) => [
    `[${e.id}](${e.source.url})`,
    e.source.date ?? '—',
    `${e.engine} ${e.engineVersion}`,
    e.model.hfId,
    `${e.hardware.gpuCount}× ${gpuName(e.hardware.gpuId)}`,
    `TP${e.hardware.tp} PP${e.hardware.pp}${e.hardware.dp > 1 ? ` DP${e.hardware.dp}` : ''}`,
    e.perf.length ? e.perf.map((p) => `${p.concurrency ?? '∞'}× ${p.inputLen ?? '?'}/${p.outputLen ?? '?'}: ${num(p.outputTokPerS, 0)} tok/s out, TTFT ${num(p.ttftMsMedian ?? p.ttftMsMean, 0)} ms`).join('; ') : '—',
    role(e.id),
  ]);
  const by = (k: string) => refs.entries.filter((e) => e.engine === k).length;
  return ['# Appendix B. Public benchmarks', '', GENERATED, '', `${refs.entries.length} entries (vLLM ${by('vllm')}, SGLang ${by('sglang')}), checked on ${refs.checkedOn}. Each links to its source.`, '', table(['Reference', 'Date', 'Engine', 'Model', 'GPUs', 'Layout', 'Measured (concurrency × input/output)', 'Use'], rows), ''].join('\n');
}

// C. Validation errors per point.
function appendixC(): string {
  const bucket = (n: number) => (n <= 8192 ? '≤ 8K' : n <= 32768 ? '≤ 32K' : n <= 131072 ? '≤ 128K' : '> 128K');
  type Row = { group: string; summary: string; declared: number; id: string; what: string; measured: number; min: number; max: number; err: number; inside: boolean };
  const rows: Row[] = [];
  for (const p of points.points) {
    if (CALIBRATION_CHECK.outliers[p.id] !== undefined) continue;
    const pr = predict(p);
    if (!pr.speedKnown) continue;
    const group = [pr.family, pr.weights.toUpperCase(), p.engine === 'vllm' ? 'vLLM' : 'SGLang', bucket(p.inputLen), gpuName(p.gpu)].join(' · ');
    const card = p.id.startsWith('5090-') ? 'RTX 5090 (measured)' : 'public benchmarks (H100 / H200 / B200 / B300)';
    const add = (what: string, v: number, r: { min: number; max: number }, declared: number) => {
      const centre = (r.min + r.max) / 2;
      const summary = [p.engine === 'vllm' ? 'vLLM' : 'SGLang', card, `${pr.family} ${pr.weights.toUpperCase()}`, what === 'TTFT (ms)' ? 'TTFT' : 'generation'].join(' | ');
      rows.push({ group, summary, declared, id: p.id, what, measured: v, min: r.min, max: r.max, err: (v - centre) / centre, inside: v >= r.min && v <= r.max });
    };
    if (p.decodeTokSPerUser !== undefined) add('tok/s per user', p.decodeTokSPerUser, pr.decode, pr.spread.decode);
    if (p.ttftMs !== undefined) add('TTFT (ms)', p.ttftMs, pr.ttft, pr.spread.prefill);
  }
  const groups = [...new Set(rows.map((r) => r.group))].sort();
  const summary = groups.map((g) => {
    const rs = rows.filter((r) => r.group === g);
    const abs = rs.map((r) => Math.abs(r.err));
    return [g, rs.length, `${rs.filter((r) => r.inside).length}/${rs.length}`, pct(median(abs)).replace('+', '±'), pct(Math.max(...abs)).replace('+', '±')];
  });
  const keys = [...new Set(rows.map((r) => r.summary))].sort();
  const byEngine = keys.map((k) => {
    const rs = rows.filter((r) => r.summary === k);
    const abs = rs.map((r) => Math.abs(r.err));
    return [...k.split(' | '), rs.length, `${(100 * abs.reduce((a, b) => a + b, 0) / abs.length).toFixed(0)} %`, `${(100 * Math.max(...abs)).toFixed(0)} %`, `±${Math.round(100 * (rs[0] as Row).declared)} %`, `${rs.filter((r) => r.inside).length}/${rs.length}`];
  });
  return [
    '# Appendix C. Validation errors per point',
    '',
    GENERATED,
    '',
    'Every measured point against the predicted range (`test/fixtures/calibration-points.json`, recomputed by `test/planner/calibration-points.test.ts`). Error = measured against the centre of the predicted range. Outliers named in `src/planner/calibration.ts` are listed in Appendix B and left out here.',
    '',
    '## C.1 By engine · card · family and format · phase',
    '',
    'Mean and worst error against the centre of the range, the error the planner declares for that case, and how many points fall inside the predicted range (exactly, without tolerance). A range under load spans pure generation to generation with the other requests’ prompts, so a point can be inside the range with an error above the declared one.',
    '',
    table(['Engine', 'Card', 'Family and format', 'Phase', 'Points', 'Mean error', 'Worst error', 'Declared', 'Inside'], byEngine),
    '',
    '## C.2 By family · format · engine · context · card',
    '',
    table(['Group', 'Points', 'Inside the range', 'Median error', 'Largest error'], summary),
    '',
    '## C.3 Weights per GPU against the engine log',
    '',
    `A format × family is verified when every computed weight matches vLLM's "Model loading took" line; a gap is the largest excess the engine showed, kept as a margin. Any other combination gets a ${Math.round(UNVERIFIED_GAP * 100)} % margin.`,
    '',
    table(['Format', 'Family', 'Status', 'Margin', 'Evidence'], WEIGHTS_CHECKS.map((c) => [c.format.toUpperCase(), c.family, c.status, `${(c.gapShare * 100).toFixed(1)} %${c.gapFixedMiB ? ` + ${c.gapFixedMiB} MiB` : ''}`, c.evidence.join('; ')])),
    '',
    '## C.4 Every point',
    '',
    table(['Point', 'Group', 'Quantity', 'Measured', 'Predicted', 'Error'], rows.map((r) => [r.id, r.group, r.what, num(r.measured), `${num(r.min)}–${num(r.max)}`, pct(r.err)])),
    '',
  ].join('\n');
}

// D. GPU specification sources.
function appendixD(): string {
  const sections = hw.gpus.map((g) =>
    [
      `## ${g.name}`,
      '',
      `\`${g.id}\` · ${g.architecture} · compute capability ${g.computeCapability} · ${g.vramGBNominal} GB ${g.memoryType} · ${num(g.memoryBandwidthGBs, 0)} GB/s · BF16 ${num(g.tflopsDense.bf16)} / FP8 ${num(g.tflopsDense.fp8)} / FP4 ${num(g.tflopsDense.fp4)} dense TFLOPS${g.tflopsDerived ? ` (derived: ${g.tflopsDerived})` : ''} · CUDA-visible ${g.cudaTotalBytes ? `${num(g.cudaTotalBytes / 2 ** 30, 2)} GiB (measured)` : g.cudaTotalGiB ? `${g.cudaTotalGiB} GiB` : 'not measured'}${
        g.nvidiaSmiTotalMiB === null && g.vramBytes === null ? ` · whole memory derived, no nvidia-smi total found: ${g.cudaTotalBytes || g.cudaTotalGiB ? 'the CUDA-visible figure' : `${g.vramGBNominal} GB sold × 0.97`}` : ''
      }`,
      '',
      table(['Fields', 'Source', 'Note'], g.sources.map((s) => [s.fields.join(', '), `[${s.title}](${s.url})`, s.note ?? ''])),
      ...(g.gaps.length ? ['', `Not published: ${g.gaps.map((x) => `${x.field} (${x.reason})`).join('; ')}.`] : []),
      '',
    ].join('\n'),
  );
  return ['# Appendix D. GPU specification sources', '', GENERATED, '', `${hw.gpus.length} NVIDIA GPUs, checked on ${hw.checkedOn}.`, '', ...sections].join('\n');
}

// E. Fitted parameters of the speed model.
function appendixE(): string {
  const r = (x: { min: number; max: number }, d = 3) => (x.min === x.max ? num(x.min, d) : `${num(x.min, d)}–${num(x.max, d)}`);
  const cols: [string, Calibration][] = [
    ['vLLM, any card', VLLM_CALIBRATION],
    ['SGLang, any card', SGLANG_CALIBRATION],
    ...(
      [
        ['dense', 'bf16'],
        ['moe', 'fp8'],
        ['hybrid', 'fp8'],
        ['mla', 'fp8'],
      ] as const
    ).map(([family, fmt]): [string, Calibration] => [`vLLM, RTX 5090, ${family}`, calibrationFor('vllm', { id: 'rtx-5090-32gb' }, fmt, family)]),
  ];
  const row = (label: string, f: (c: Calibration) => string) => [label, ...cols.map(([, c]) => f(c))];
  const rows = [
    row('engine version', (c) => c.engineVersion),
    row('η_w: weight bandwidth share in decode', (c) => r(c.decodeWeightEff)),
    row('η_kv: KV read bandwidth share', (c) => r(c.kvReadEff)),
    row('η_mfu: compute share in decode', (c) => r(c.decodeMfu)),
    row('η_prefill: compute share in prefill', (c) => r(c.prefillMfu)),
    ...[4096, 32768, 131072, 1048576].map((t) => row(`η_attn at ${tok(t)} tokens`, (c) => r(c.prefillAttnEff(t)))),
    row('c_step: per decode step (ms)', (c) => r(c.stepOverheadMs, 2)),
    row('c_layer: per layer and step (µs)', (c) => r(c.layerOverheadUs, 2)),
    row('c_moe: extra per MoE layer (µs)', (c) => r(c.moeLayerExtraUs, 2)),
    row('c_expert: per touched expert (µs)', (c) => r(c.moeExpertUs, 2)),
    row('c_seq: per sequence and layer (µs)', (c) => r(c.seqLayerUs, 3)),
    row('c_recurrent: per prompt token and recurrent layer (µs)', (c) => (c.recurrentTokenUs ? r(c.recurrentTokenUs, 3) : '—')),
    row('request overhead (ms)', (c) => r(c.requestOverheadMs, 0)),
    row('s_mfu FP8 / FP4', (c) => `${num(c.formatMfuScale.fp8, 3)} / ${num(c.formatMfuScale.fp4, 3)}`),
    row('s_bw FP8 / FP4', (c) => `${num(c.formatBwScale.fp8, 3)} / ${num(c.formatBwScale.fp4, 3)}`),
    row('all-reduce latency NVLink / PCIe P2P / PCIe host (µs)', (c) => `${c.allReduceLatencyUs.nvlink} / ${c.allReduceLatencyUs['pcie-p2p']} / ${c.allReduceLatencyUs['pcie-host']}`),
    row('η_link: link bandwidth share', (c) => r(c.linkEff)),
    row('declared spread: generation / prompt reading', (c) => (c.spread ? `±${Math.round(c.spread.decode * 100)} % / ±${Math.round(c.spread.prefill * 100)} %` : '—')),
  ];
  return ['# Appendix E. Fitted parameters of the speed model', '', GENERATED, '', 'The constants of section 7 as the code holds them (`src/planner/calibration.ts`). Efficiencies above 1 mean the card runs above the boost clock its datasheet TFLOPS assume: the values are effective, not physical.', '', table(['Parameter', ...cols.map(([n]) => n)], rows), ''].join(String.fromCharCode(10));
}

