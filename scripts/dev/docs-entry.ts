// Writes the appendices of docs/METHODOLOGY.md from the repository's data (development only; run after any change
// to the data, the calibration or the fixtures): every number in them comes from these files, none is typed by hand.
//   A. calibration runs on the RTX 5090      test/fixtures/rtx5090/{speed,speed-long,measurements}.json
//   B. public benchmarks                      data/references.json, test/fixtures/calibration-points.json
//   C. validation errors per point            the speed model against every measured point (as the test suite does)
//   D. GPU specification sources              data/hardware.json
//   E. fitted parameters of the speed model   src/planner/calibration.ts
// and NOTICE.md, the third-party data with its sources and licences (scripts/dev/notice-lib.ts).
