// NOTICE.md: the third-party data the repository and its releases carry, with their sources and licences. Written by
// `npm run dev:docs` from the data itself (data/models/*/source.json, data/models.json, data/references.json,
// data/hardware.json); test/docs/notice.test.ts checks that it matches.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import type * as Pack from '../pack-models.mjs';

interface Source {
  repo: string;
  revision: string;
  license: string | null;
  licenseName: string | null;
  licenseLink: string | null;
  readable: boolean;
  gated: boolean | string;
  /** Why its files are not kept: its licence may not allow passing them on. */
  withheld?: string;
}

/** Every repo saved under data/models (models and their quantized variants), by name. */
function sources(dir: string): Source[] {
  const out: Source[] = [];
  const walk = (d: string) => {
    if (existsSync(path.join(d, 'source.json'))) out.push(JSON.parse(readFileSync(path.join(d, 'source.json'), 'utf8')) as Source);
    for (const e of readdirSync(d, { withFileTypes: true })) if (e.isDirectory()) walk(path.join(d, e.name));
  };
  walk(dir);
  return out.sort((a, b) => a.repo.localeCompare(b.repo));
}

const cell = (s: string) => s.replace(/\|/g, '\\|');

/** licenses/index.json: the licence texts of each saved repository (files of licenses/). */
export interface LicenceIndex {
  repos: Record<string, { revision: string; license: string; files: string[] }>;
}

export async function noticeText(root: string): Promise<string> {
  // Loaded at run time, not bundled: run directly, it would start its own command line.
  const { NOT_REDISTRIBUTED } = (await import(pathToFileURL(path.join(root, 'scripts', 'pack-models.mjs')).href)) as typeof Pack;
  const read = (p: string) => JSON.parse(readFileSync(path.join(root, p), 'utf8')) as unknown;
  const catalog = read('data/models.json') as { models: { repo: string; license: { name: string; url: string } }[] };
  const licenceOf = new Map(catalog.models.map((m) => [m.repo, m.license]));
  const refs = read('data/references.json') as { entries: { source: { url: string; title: string } }[] };
  const hw = read('data/hardware.json') as { gpus: { sources: { url: string; title: string }[] }[] };
  const texts = (read('licenses/index.json') as LicenceIndex).repos;

  const repos = sources(path.join(root, 'data', 'models'));
  const rows = repos.map((s) => {
    const own = licenceOf.get(s.repo);
    const name = own?.name ?? (s.license === 'other' || s.license === null ? (s.licenseName ?? 'see the repository') : s.license);
    const link = own?.url ?? s.licenseLink ?? `https://huggingface.co/${s.repo}`;
    const bundled = s.withheld ? `no, nor saved here: ${s.withheld}` : !s.readable || s.gated ? 'no (gated: not saved)' : s.repo in NOT_REDISTRIBUTED ? `no: ${NOT_REDISTRIBUTED[s.repo]}` : 'yes';
    const copies = (texts[s.repo]?.files ?? []).map((t) => `[${t}](licenses/${t})`).join(', ') || '—';
    return `| [${s.repo}](https://huggingface.co/${s.repo}) | \`${s.revision.slice(0, 12)}\` | [${cell(name)}](${link}) | ${copies} | ${cell(bundled)} |`;
  });
  // The statements NVIDIA's licences require in a notice file of whoever passes their files on.
  const statements = [
    ['nvidia-open-model-license', 'Licensed by NVIDIA Corporation under the NVIDIA Open Model License'],
    ['nvidia-nemotron-open-model-license', 'Licensed by NVIDIA Corporation under the NVIDIA Nemotron Model License.'],
  ].flatMap(([licence, statement]) => {
    const under = Object.entries(texts)
      .filter(([, t]) => t.license === licence)
      .map(([repo]) => repo)
      .sort();
    return under.length ? [`- ${under.join(', ')}: "${statement}"`] : [];
  });
  const unique = (list: { url: string; title: string }[]) => [...new Map(list.map((x) => [x.url, x.title])).entries()].sort((a, b) => a[0].localeCompare(b[0]));
  const benchmarks = unique(refs.entries.map((e) => e.source));
  const specs = unique(hw.gpus.flatMap((g) => g.sources));

  return [
    '# Third-party data',
    '',
    '<!-- Generated by `npm run dev:docs` from the repository data. Do not edit by hand. -->',
    '',
    'The code of this project is under the MIT licence ([LICENSE](LICENSE)). The repository and its releases also carry',
    'data from third parties, which keep their own terms. They are listed here with their sources.',
    '',
    '## Model metadata',
    '',
    'For each Hugging Face repository below, `data/models/` holds its `config.json`, `generation_config.json`, `params.json`,',
    'safetensors index and safetensors headers (tensor names, shapes and types: no weights), read at the revision shown.',
    'The models built into the program (the models pack of the releases) are the same files. Each repository is under its',
    "own licence; the link leads to it. Gated repositories are not saved, and neither are those whose licence may not allow passing",
    'their files on (their record says why; the command reads them from Hugging Face).',
    '',
    '| Repository | Revision | Licence | Licence text | In the models pack |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
    "The full text of every licence above is in [licenses/](licenses/): the repository's own licence file at the revision",
    "shown, and the official text of the licence it declares (a quantization also carries its base model's). Each file names",
    'its source on top.',
    '',
    '### Notices the licences require',
    '',
    ...statements,
    '- LGAI-EXAONE/K-EXAONE-2.0-750B-A37B and its quantizations: the NOTICE of the repository, in',
    '  [licenses/k-exaone-notice.txt](licenses/k-exaone-notice.txt).',
    '',
    '## Public benchmarks',
    '',
    '`data/references.json` and `test/fixtures/calibration-points.json` quote figures (throughput, memory, settings) and',
    'short log lines from these public pages:',
    '',
    ...benchmarks.map(([url, title]) => `- [${cell(title)}](${url})`),
    '',
    '## GPU specifications',
    '',
    '`data/hardware.json` takes its values from these NVIDIA and PCI-SIG documents (and a few public measurements, cited',
    'field by field in the file):',
    '',
    ...specs.map(([url, title]) => `- [${cell(title)}](${url})`),
    '',
    '## Engine source code',
    '',
    '`data/compat.json` cites lines of vLLM (Apache-2.0, <https://github.com/vllm-project/vllm>) and SGLang (Apache-2.0,',
    '<https://github.com/sgl-project/sglang>) at the release tags it was checked on, with a short anchor text from each.',
    '',
    '## Trademarks',
    '',
    'NVIDIA, GeForce, RTX, Hopper, Blackwell and the names of NVIDIA products are trademarks of NVIDIA Corporation. vLLM,',
    'SGLang, Hugging Face and the model names belong to their respective owners. This project is not affiliated with or',
    'endorsed by any of them.',
    '',
  ].join('\n');
}
